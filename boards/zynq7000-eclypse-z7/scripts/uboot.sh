#!/usr/bin/env bash
# =============================================================================
#  scripts/uboot.sh - build the first-stage loader and the bootloader: BOOT.BIN + u-boot.img
# =============================================================================
#
#  The Zynq-7000 BootROM loads ONE small program from the SD card, BOOT.BIN, into the
#  256 KiB on-chip RAM (OCM). On this board that program is NOT Xilinx's FSBL but the
#  SPL ("secondary program loader") of U-Boot itself. It:
#
#    1. runs ps7_init: ~1000 register writes that start the PLLs, bring up the DDR3L,
#       set the clock dividers and mux the MIO pins (UART0, SD0, Ethernet, USB...)
#    2. initialises the UART and the SD controller
#    3. loads  u-boot.img  (U-Boot proper) from the FAT partition into DDR and jumps to it
#
#  Both binaries come from ONE U-Boot build:
#
#    spl/boot.bin   = spl/u-boot-spl.bin wrapped by `mkimage -T zynqimage` in the
#                     Zynq boot-image header the BootROM expects  ->  build/deploy/BOOT.BIN
#    u-boot.img     = U-Boot proper (+ the device tree) as a FIT image   ->  build/deploy/u-boot.img
#
#  Steps (each is a standalone sub-command):
#
#    ps7       fetch/prepare ps7_init_gpl.c + .h (the hardware design's PS configuration)
#    uboot     configure and compile U-Boot, deploy BOOT.BIN + u-boot.img
#    all       both (default)
#
#  Usage: scripts/uboot.sh [all|ps7|uboot|menuconfig|clean]
# =============================================================================
# shellcheck source=lib/common.sh
source "$(dirname "${BASH_SOURCE[0]}")/lib/common.sh"
strict_mode
load_config

UBOOT_SRC="$SRC_DIR/u-boot"
UBOOT_OUT="$WORK_DIR/u-boot"
PS7_DIR="$WORK_DIR/ps7-init"
CUSTOM_DTS_DIR="$TOP_DIR/custom/dts"
FRAGMENT_DIR="$TOP_DIR/config/uboot"

umake() { MAKE_ARCH=arm run_make "$1" "$UBOOT_SRC" O="$UBOOT_OUT" DEVICE_TREE="$UBOOT_DEVICE_TREE" "${@:2}"; }

# -----------------------------------------------------------------------------
do_ps7() {
  need_cmd python3
  section "PS7 initialisation (ps7_init_gpl.c / .h)"
  explain "Before the DDR works, the PS needs its PLLs, DDR controller, clock dividers and MIO" \
          "muxes configured. Vivado writes those register values into ps7_init_gpl.c for a" \
          "given hardware design; the SPL compiles the file in and calls ps7_init() first." \
          "U-Boot ships such files for a few boards, none for the Eclypse Z7, so we take one from the" \
          "hardware design of the board (see docs/03-uboot-spl.md for provenance and licence)."
  local src=$PS7_INIT_SRC
  if [[ -n $src ]]; then
    info "Using your PS7 initialisation: $src"
    [[ $DRY_RUN == 1 || -e $src ]] || die "PS7_INIT_SRC=$src does not exist"
  else
    src="$DL_DIR/${PS7_INIT_URL##*/}"
    fetch "$PS7_INIT_URL" "$src" "$PS7_INIT_SHA256"
  fi
  run "Extract the two files, make them compile inside U-Boot (CRLF -> LF, '()' -> '(void)')" \
    python3 -I "$TOP_DIR/scripts/lib/ps7_prepare.py" "$src" "$PS7_DIR"
}

# -----------------------------------------------------------------------------
do_source() {
  section "U-Boot source: $UBOOT_BRANCH"
  git_checkout "u-boot" "$UBOOT_REPO" "$UBOOT_BRANCH" "$UBOOT_REV" "$UBOOT_SRC"
  apply_patches u-boot "$UBOOT_SRC"
  # The board's device tree is ours (custom/dts), the patch above only adds it to the
  # list of trees that get compiled.
  local f
  for f in "$CUSTOM_DTS_DIR/$UBOOT_DEVICE_TREE".dts*; do
    [[ -e $f ]] || die "custom/dts/$UBOOT_DEVICE_TREE.dts not found"
    run "Copy $(basename "$f") into U-Boot's device tree directory" cp "$f" "$UBOOT_SRC/arch/arm/dts/"
  done
}

# -----------------------------------------------------------------------------
do_uboot() {
  use_toolchain
  need_cmd python3 swig dtc bison flex
  do_ps7
  do_source
  section "Configuring U-Boot ($UBOOT_DEFCONFIG)"
  explain "xilinx_zynq_virt_defconfig is mainline's generic Zynq-7000 configuration: SPL on," \
          "distro boot, FIT images. We add config/uboot/eclypse-z7.config (the board's" \
          "device tree) and one line that points the SPL at our ps7_init_gpl.c."
  run "Create the output directory" mkdir -p "$UBOOT_OUT"
  umake "Create .config from configs/$UBOOT_DEFCONFIG" "$UBOOT_DEFCONFIG"
  local frag="$UBOOT_OUT/ps7-init.config"
  explain "Writing $frag: CONFIG_XILINX_PS_INIT_FILE=\"$PS7_DIR/ps7_init_gpl.c\""
  if [[ $DRY_RUN != 1 ]]; then
    printf '# generated by scripts/uboot.sh\nCONFIG_XILINX_PS_INIT_FILE="%s"\n' "$PS7_DIR/ps7_init_gpl.c" > "$frag"
  fi
  run "Merge the fragments on top of the defconfig" \
    env ARCH=arm CROSS_COMPILE="$CROSS_COMPILE" \
    "$UBOOT_SRC/scripts/kconfig/merge_config.sh" -m -O "$UBOOT_OUT" "$UBOOT_OUT/.config" \
      "$FRAGMENT_DIR"/*.config "$frag"
  umake "Resolve dependencies of the merged options" olddefconfig

  section "Compiling U-Boot with $JOBS jobs"
  explain "One make builds spl/u-boot-spl (first stage), spl/boot.bin (the Zynq boot image) and" \
          "u-boot.img (U-Boot proper). The first one runs from on-chip RAM, the second from DDR."
  umake "Compile SPL, U-Boot proper and the boot image" all

  if [[ $DRY_RUN != 1 ]]; then
    need_file "$UBOOT_OUT/spl/boot.bin" "$UBOOT_OUT/u-boot.img"
    # The BootROM can run an SPL of at most ~192 KiB (the OCM minus the top 64 KiB it keeps for itself).
    local sz; sz=$(stat -c %s "$UBOOT_OUT/spl/boot.bin")
    ((sz <= 192 * 1024)) || die "spl/boot.bin is $sz bytes: larger than the 192 KiB the BootROM can load"
  fi
  run "Create the deploy directory" mkdir -p "$DEPLOY_DIR"
  run "Deploy the first-stage boot image as BOOT.BIN (the name the BootROM looks for)" \
    cp "$UBOOT_OUT/spl/boot.bin" "$DEPLOY_DIR/BOOT.BIN"
  run "Deploy U-Boot proper (a FIT image, loaded by the SPL)" \
    cp "$UBOOT_OUT/u-boot.img" "$DEPLOY_DIR/u-boot.img"
  run "Keep the SPL ELF too (for a debugger, and to read its addresses)" \
    cp "$UBOOT_OUT/spl/u-boot-spl" "$DEPLOY_DIR/u-boot-spl.elf"
  if [[ $DRY_RUN != 1 ]]; then
    info "BOOT.BIN: $(stat -c %s "$DEPLOY_DIR/BOOT.BIN") bytes, u-boot.img: $(stat -c %s "$DEPLOY_DIR/u-boot.img") bytes"
    if [[ -x $UBOOT_OUT/tools/mkimage ]]; then
      "$UBOOT_OUT/tools/mkimage" -l "$DEPLOY_DIR/BOOT.BIN" | sed 's/^/  /'
    fi
  fi
}

do_menuconfig() {
  [[ -f $UBOOT_OUT/.config ]] || do_uboot
  use_toolchain
  umake "Open U-Boot's interactive configuration menu" menuconfig
  info "Save a fragment of your changes in config/uboot/*.config (see docs/08-customizing.md)."
}

do_clean() {
  section "Cleaning U-Boot build (the checkout is kept)"
  run "Remove the U-Boot build directory and the prepared PS7 files" rm -rf "$UBOOT_OUT" "$PS7_DIR"
  run "Remove the deployed boot files" rm -f "$DEPLOY_DIR/BOOT.BIN" "$DEPLOY_DIR/u-boot.img" "$DEPLOY_DIR/u-boot-spl.elf"
}

main() {
  local target=${1:-all}
  [[ $target == menuconfig ]] || start_log "uboot-$target"
  case $target in
    all|uboot)  do_uboot ;;
    ps7)        do_ps7 ;;
    menuconfig) do_menuconfig ;;
    clean)      do_clean ;;
    *) die "unknown target '$target' (all|ps7|uboot|menuconfig|clean)" ;;
  esac
}

main "$@"
